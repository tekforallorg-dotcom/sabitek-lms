import { NextRequest } from 'next/server'
import { createClient } from '@supabase/supabase-js'
import { extractBearerToken } from '@/lib/validations'
import { apiSuccess, ApiErrors } from '@/lib/api-response'
import { addProgramCourseSchema, reorderProgramCoursesSchema } from '@/lib/validations/program'

const supabaseAdmin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
)

interface RouteParams {
  params: Promise<{ id: string }>
}

/**
 * GET /api/programs/[id]/courses
 * List courses in a program
 */
export async function GET(request: NextRequest, { params }: RouteParams) {
  try {
    const { id } = await params

    const token = extractBearerToken(request.headers.get('authorization'))
    if (!token) {
      return ApiErrors.unauthorized()
    }

    const { data: { user }, error: authError } = await supabaseAdmin.auth.getUser(token)
    if (authError || !user) {
      return ApiErrors.unauthorized()
    }

    // Verify program exists and user has access
    const { data: program } = await supabaseAdmin
      .from('programs')
      .select('institution_id, visibility')
      .eq('id', id)
      .single()

    if (!program) {
      return ApiErrors.notFound('Program not found')
    }

    // Check membership
    const { data: membership } = await supabaseAdmin
      .from('institution_members')
      .select('role')
      .eq('institution_id', program.institution_id)
      .eq('user_id', user.id)
      .eq('status', 'active')
      .single()

    if (!membership && program.visibility !== 'public') {
      return ApiErrors.forbidden('Not authorized to view program courses')
    }

    // Fetch courses
    const { data: courses, error } = await supabaseAdmin
      .from('program_courses')
      .select(`
        id,
        position,
        is_required,
        unlock_rules,
        added_at,
        course:courses(
          id,
          title,
          slug,
          description,
          thumbnail,
          instructor_id,
          lessons_count,
          duration_hours
        )
      `)
      .eq('program_id', id)
      .order('position', { ascending: true })

    if (error) {
      console.error('Error fetching program courses:', error)
      return ApiErrors.internal('Failed to fetch courses')
    }

    return apiSuccess({ courses: courses || [] })

  } catch (error) {
    console.error('Program courses GET error:', error)
    return ApiErrors.internal()
  }
}

/**
 * POST /api/programs/[id]/courses
 * Add a course to the program
 */
export async function POST(request: NextRequest, { params }: RouteParams) {
  try {
    const { id } = await params

    const token = extractBearerToken(request.headers.get('authorization'))
    if (!token) {
      return ApiErrors.unauthorized()
    }

    const { data: { user }, error: authError } = await supabaseAdmin.auth.getUser(token)
    if (authError || !user) {
      return ApiErrors.unauthorized()
    }

    // Verify program exists
    const { data: program } = await supabaseAdmin
      .from('programs')
      .select('institution_id')
      .eq('id', id)
      .single()

    if (!program) {
      return ApiErrors.notFound('Program not found')
    }

    // Verify user can manage program
    const { data: membership } = await supabaseAdmin
      .from('institution_members')
      .select('role')
      .eq('institution_id', program.institution_id)
      .eq('user_id', user.id)
      .eq('status', 'active')
      .single()

    if (!membership || !['institution_admin', 'program_manager'].includes(membership.role)) {
      return ApiErrors.forbidden('Not authorized to add courses')
    }

    const body = await request.json()
    const validatedData = addProgramCourseSchema.parse(body)

    // Verify course exists
    const { data: course } = await supabaseAdmin
      .from('courses')
      .select('id, title')
      .eq('id', validatedData.course_id)
      .single()

    if (!course) {
      return ApiErrors.notFound('Course not found')
    }

    // Check if course already in program
    const { data: existing } = await supabaseAdmin
      .from('program_courses')
      .select('id')
      .eq('program_id', id)
      .eq('course_id', validatedData.course_id)
      .single()

    if (existing) {
      return ApiErrors.badRequest('Course already in program')
    }

    // Get max position if not specified
    let position = validatedData.position
    if (position === 0) {
      const { data: maxPos } = await supabaseAdmin
        .from('program_courses')
        .select('position')
        .eq('program_id', id)
        .order('position', { ascending: false })
        .limit(1)
        .single()

      position = (maxPos?.position || 0) + 1
    }

    // Add course to program
    const { data: programCourse, error } = await supabaseAdmin
      .from('program_courses')
      .insert({
        program_id: id,
        course_id: validatedData.course_id,
        position,
        is_required: validatedData.is_required,
        unlock_rules: validatedData.unlock_rules,
        added_by: user.id,
      })
      .select(`
        id,
        position,
        is_required,
        unlock_rules,
        course:courses(id, title, slug, thumbnail)
      `)
      .single()

    if (error) {
      console.error('Error adding course to program:', error)
      return ApiErrors.internal('Failed to add course')
    }

    // Audit log
    await supabaseAdmin.from('audit_logs').insert({
      actor_user_id: user.id,
      action: 'program.course_added',
      entity_type: 'program',
      entity_id: id,
      new_state: { course_id: validatedData.course_id },
    })

    return apiSuccess(programCourse, 201)

  } catch (error) {
    if (error instanceof Error && error.name === 'ZodError') {
      return ApiErrors.badRequest('Invalid input', error)
    }
    console.error('Program courses POST error:', error)
    return ApiErrors.internal()
  }
}

/**
 * PUT /api/programs/[id]/courses
 * Reorder courses in the program
 */
export async function PUT(request: NextRequest, { params }: RouteParams) {
  try {
    const { id } = await params

    const token = extractBearerToken(request.headers.get('authorization'))
    if (!token) {
      return ApiErrors.unauthorized()
    }

    const { data: { user }, error: authError } = await supabaseAdmin.auth.getUser(token)
    if (authError || !user) {
      return ApiErrors.unauthorized()
    }

    // Verify program exists and user can manage
    const { data: program } = await supabaseAdmin
      .from('programs')
      .select('institution_id')
      .eq('id', id)
      .single()

    if (!program) {
      return ApiErrors.notFound('Program not found')
    }

    const { data: membership } = await supabaseAdmin
      .from('institution_members')
      .select('role')
      .eq('institution_id', program.institution_id)
      .eq('user_id', user.id)
      .eq('status', 'active')
      .single()

    if (!membership || !['institution_admin', 'program_manager'].includes(membership.role)) {
      return ApiErrors.forbidden('Not authorized to reorder courses')
    }

    const body = await request.json()
    const { course_ids } = reorderProgramCoursesSchema.parse(body)

    // Update positions
    const updates = course_ids.map((courseId, index) =>
      supabaseAdmin
        .from('program_courses')
        .update({ position: index })
        .eq('program_id', id)
        .eq('course_id', courseId)
    )

    await Promise.all(updates)

    return apiSuccess({ message: 'Courses reordered successfully' })

  } catch (error) {
    if (error instanceof Error && error.name === 'ZodError') {
      return ApiErrors.badRequest('Invalid input', error)
    }
    console.error('Program courses PUT error:', error)
    return ApiErrors.internal()
  }
}